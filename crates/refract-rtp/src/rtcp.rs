/// Bounded RTCP compound packet generator.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RtcpBuilder {
    bytes: [u8; MAX_RTCP_COMPOUND_LEN],
    len: usize,
}

impl RtcpBuilder {
    /// Creates an empty RTCP builder.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::RtcpBuilder;
    /// assert!(RtcpBuilder::new().as_slice().is_empty());
    /// ```
    #[must_use]
    pub const fn new() -> Self {
        Self {
            bytes: [0; MAX_RTCP_COMPOUND_LEN],
            len: 0,
        }
    }

    /// Appends a Sender Report.
    ///
    /// # Errors
    ///
    /// Returns an error if the compound packet would exceed 1500 bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::{RtcpBuilder, SenderReport};
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_sender_report(SenderReport {
    ///     sender_ssrc: 1,
    ///     ntp_msw: 0,
    ///     ntp_lsw: 0,
    ///     rtp_timestamp: 0,
    ///     packet_count: 0,
    ///     octet_count: 0,
    /// })?;
    /// assert_eq!(builder.as_slice()[1], 200);
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    pub fn push_sender_report(&mut self, sr: SenderReport) -> RtpResult<()> {
        self.reserve_packet(PT_SR, 0, 24, |body| {
            write_u32(&mut body[0..4], sr.sender_ssrc);
            write_u32(&mut body[4..8], sr.ntp_msw);
            write_u32(&mut body[8..12], sr.ntp_lsw);
            write_u32(&mut body[12..16], sr.rtp_timestamp);
            write_u32(&mut body[16..20], sr.packet_count);
            write_u32(&mut body[20..24], sr.octet_count);
        })
    }

    /// Appends a Receiver Report without report blocks.
    ///
    /// # Errors
    ///
    /// Returns an error if the compound packet would exceed 1500 bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::RtcpBuilder;
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_receiver_report(1)?;
    /// assert_eq!(builder.as_slice()[1], 201);
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    pub fn push_receiver_report(&mut self, sender_ssrc: u32) -> RtpResult<()> {
        self.reserve_packet(PT_RR, 0, 4, |body| write_u32(body, sender_ssrc))
    }

    /// Appends a BYE packet for one SSRC.
    ///
    /// # Errors
    ///
    /// Returns an error if the compound packet would exceed 1500 bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::RtcpBuilder;
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_bye(7)?;
    /// assert_eq!(builder.as_slice()[0] & 0x1f, 1);
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    pub fn push_bye(&mut self, ssrc: u32) -> RtpResult<()> {
        self.reserve_packet(PT_BYE, 1, 4, |body| write_u32(body, ssrc))
    }

    /// Appends a generic NACK packet.
    ///
    /// # Errors
    ///
    /// Returns an error if the compound packet would exceed 1500 bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::RtcpBuilder;
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_nack(1, 2, 10, 0)?;
    /// assert_eq!(builder.as_slice()[1], 205);
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    pub fn push_nack(
        &mut self,
        sender_ssrc: u32,
        media_ssrc: u32,
        pid: u16,
        blp: u16,
    ) -> RtpResult<()> {
        self.reserve_packet(PT_RTPFB, FMT_NACK, 12, |body| {
            write_u32(&mut body[0..4], sender_ssrc);
            write_u32(&mut body[4..8], media_ssrc);
            write_u16(&mut body[8..10], pid);
            write_u16(&mut body[10..12], blp);
        })
    }

    /// Appends a PLI packet.
    ///
    /// # Errors
    ///
    /// Returns an error if the compound packet would exceed 1500 bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::RtcpBuilder;
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_pli(1, 2)?;
    /// assert_eq!(builder.as_slice()[0] & 0x1f, 1);
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    pub fn push_pli(&mut self, sender_ssrc: u32, media_ssrc: u32) -> RtpResult<()> {
        self.reserve_packet(PT_PSFB, FMT_PLI, 8, |body| {
            write_u32(&mut body[0..4], sender_ssrc);
            write_u32(&mut body[4..8], media_ssrc);
        })
    }

    /// Appends a REMB packet with a pre-encoded FCI body.
    ///
    /// # Errors
    ///
    /// Returns an error if the FCI length is not a 32-bit multiple or the
    /// compound packet would exceed 1500 bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::RtcpBuilder;
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_remb(1, 2, b"REMB\0\0\0\0")?;
    /// assert_eq!(builder.as_slice()[1], 206);
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    pub fn push_remb(&mut self, sender_ssrc: u32, media_ssrc: u32, fci: &[u8]) -> RtpResult<()> {
        let body_len = 8 + fci.len();
        if !body_len.is_multiple_of(4) {
            return Err(RtpError::MalformedRtcp {
                packet_type: PT_PSFB,
                reason: RtcpErrorReason::CountLengthMismatch,
            });
        }
        self.reserve_packet(PT_PSFB, FMT_REMB, body_len, |body| {
            write_u32(&mut body[0..4], sender_ssrc);
            write_u32(&mut body[4..8], media_ssrc);
            body[8..].copy_from_slice(fci);
        })
    }

    /// Returns the generated compound bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::RtcpBuilder;
    /// assert!(RtcpBuilder::new().as_slice().is_empty());
    /// ```
    #[must_use]
    pub const fn as_slice(&self) -> &[u8] {
        self.bytes.split_at(self.len).0
    }

    /// Returns the Stage 1 stability marker for this public API.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::{rtcp::RtcpBuilder, Stability};
    /// assert_eq!(RtcpBuilder::new().stability(), Stability::Stage1);
    /// ```
    #[must_use]
    pub const fn stability(&self) -> Stability {
        Stability::Stage1
    }

    fn reserve_packet(
        &mut self,
        packet_type: u8,
        count: u8,
        body_len: usize,
        fill: impl FnOnce(&mut [u8]),
    ) -> RtpResult<()> {
        if !body_len.is_multiple_of(4) {
            return Err(RtpError::MalformedRtcp {
                packet_type,
                reason: RtcpErrorReason::CountLengthMismatch,
            });
        }
        let packet_len = RTCP_HEADER_LEN + body_len;
        let Some(new_len) = self.len.checked_add(packet_len) else {
            return Err(RtpError::RtcpCompoundTooLarge {
                len: usize::MAX,
                max: MAX_RTCP_COMPOUND_LEN,
            });
        };
        if new_len > MAX_RTCP_COMPOUND_LEN {
            return Err(RtpError::RtcpCompoundTooLarge {
                len: new_len,
                max: MAX_RTCP_COMPOUND_LEN,
            });
        }
        let words_minus_one =
            u16::try_from(packet_len / 4 - 1).map_err(|_| RtpError::RtcpCompoundTooLarge {
                len: packet_len,
                max: MAX_RTCP_COMPOUND_LEN,
            })?;
        let start = self.len;
        self.bytes[start] = (RTCP_VERSION << VERSION_SHIFT) | (count & COUNT_MASK);
        self.bytes[start + 1] = packet_type;
        write_u16(&mut self.bytes[start + 2..start + 4], words_minus_one);
        fill(&mut self.bytes[start + RTCP_HEADER_LEN..new_len]);
        self.len = new_len;
        Ok(())
    }
}

impl Default for RtcpBuilder {
    fn default() -> Self {
        Self::new()
    }
}

fn parse_packet(count: u8, packet_type: u8, body: &[u8]) -> RtpResult<RtcpPacket<'_>> {
    match packet_type {
        PT_SR => parse_sr(count, body),
        PT_RR => parse_rr(count, body),
        PT_SDES => Ok(RtcpPacket::Sdes {
            count,
            chunks: body,
        }),
        PT_BYE => Ok(RtcpPacket::Bye { count, body }),
        PT_APP => Ok(RtcpPacket::App {
            subtype: count,
            body,
        }),
        PT_RTPFB => parse_rtpfb(count, body),
        PT_PSFB => parse_psfb(count, body),
        PT_XR => parse_xr(body),
        _ => Err(RtpError::MalformedRtcp {
            packet_type,
            reason: RtcpErrorReason::UnsupportedFeedbackFormat,
        }),
    }
}

fn parse_sr(count: u8, body: &[u8]) -> RtpResult<RtcpPacket<'_>> {
    let needed = 24 + usize::from(count) * 24;
    if body.len() < needed {
        return Err(RtpError::MalformedRtcp {
            packet_type: PT_SR,
            reason: RtcpErrorReason::BodyTooShort,
        });
    }
    Ok(RtcpPacket::SenderReport(SenderReport {
        sender_ssrc: read_u32(&body[0..4]),
        ntp_msw: read_u32(&body[4..8]),
        ntp_lsw: read_u32(&body[8..12]),
        rtp_timestamp: read_u32(&body[12..16]),
        packet_count: read_u32(&body[16..20]),
        octet_count: read_u32(&body[20..24]),
    }))
}

fn parse_rr(count: u8, body: &[u8]) -> RtpResult<RtcpPacket<'_>> {
    let needed = 4 + usize::from(count) * 24;
    if body.len() < needed {
        return Err(RtpError::MalformedRtcp {
            packet_type: PT_RR,
            reason: RtcpErrorReason::BodyTooShort,
        });
    }
    Ok(RtcpPacket::ReceiverReport(ReceiverReport {
        sender_ssrc: read_u32(&body[0..4]),
        reports: &body[4..needed],
    }))
}

fn parse_rtpfb(count: u8, body: &[u8]) -> RtpResult<RtcpPacket<'_>> {
    if body.len() < 8 {
        return Err(RtpError::MalformedRtcp {
            packet_type: PT_RTPFB,
            reason: RtcpErrorReason::BodyTooShort,
        });
    }
    let sender_ssrc = read_u32(&body[0..4]);
    let media_ssrc = read_u32(&body[4..8]);
    match count {
        FMT_NACK => Ok(RtcpPacket::Rtpfb(RtpFeedback::Nack {
            sender_ssrc,
            media_ssrc,
            entries: &body[8..],
        })),
        FMT_TRANSPORT_CC => Ok(RtcpPacket::Rtpfb(RtpFeedback::TransportCc {
            sender_ssrc,
            media_ssrc,
            body: &body[8..],
        })),
        _ => Err(RtpError::MalformedRtcp {
            packet_type: PT_RTPFB,
            reason: RtcpErrorReason::UnsupportedFeedbackFormat,
        }),
    }
}

fn parse_psfb(count: u8, body: &[u8]) -> RtpResult<RtcpPacket<'_>> {
    if body.len() < 8 {
        return Err(RtpError::MalformedRtcp {
            packet_type: PT_PSFB,
            reason: RtcpErrorReason::BodyTooShort,
        });
    }
    let sender_ssrc = read_u32(&body[0..4]);
    let media_ssrc = read_u32(&body[4..8]);
    match count {
        FMT_PLI => Ok(RtcpPacket::Psfb(PayloadFeedback::Pli {
            sender_ssrc,
            media_ssrc,
        })),
        FMT_FIR => Ok(RtcpPacket::Psfb(PayloadFeedback::Fir {
            sender_ssrc,
            media_ssrc,
            entries: &body[8..],
        })),
        FMT_REMB => Ok(RtcpPacket::Psfb(PayloadFeedback::Remb {
            sender_ssrc,
            media_ssrc,
            body: &body[8..],
        })),
        _ => Err(RtpError::MalformedRtcp {
            packet_type: PT_PSFB,
            reason: RtcpErrorReason::UnsupportedPayloadFeedbackFormat,
        }),
    }
}

fn parse_xr(body: &[u8]) -> RtpResult<RtcpPacket<'_>> {
    if body.len() < 4 {
        return Err(RtpError::MalformedRtcp {
            packet_type: PT_XR,
            reason: RtcpErrorReason::BodyTooShort,
        });
    }
    Ok(RtcpPacket::Xr {
        sender_ssrc: read_u32(&body[0..4]),
        blocks: &body[4..],
    })
}

