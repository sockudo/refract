//! Defensive RTCP compound packet parsing and bounded packet generation.
//!
//! Compound packets are capped at 1500 bytes. The parser validates each RTCP
//! length field before exposing borrowed packet bodies.
//!
//! # Examples
//!
//! ```
//! # use refract_rtp::rtcp::{RtcpBuilder, RtcpCompound};
//! let mut builder = RtcpBuilder::new();
//! builder.push_bye(7)?;
//! let packets = RtcpCompound::parse(builder.as_slice())?.collect::<Result<Vec<_>, _>>()?;
//! assert_eq!(packets.len(), 1);
//! # Ok::<(), refract_rtp::RtpError>(())
//! ```

use crate::{
    RtpError, Stability,
    error::{RtcpErrorReason, RtpResult},
    header::{read_u16, read_u32, write_u16, write_u32},
};

/// Maximum RTCP compound packet length accepted or generated by this crate.
pub const MAX_RTCP_COMPOUND_LEN: usize = 1_500;

const RTCP_HEADER_LEN: usize = 4;
const RTCP_VERSION: u8 = 2;
const VERSION_SHIFT: u8 = 6;
const COUNT_MASK: u8 = 0x1f;
const PT_SR: u8 = 200;
const PT_RR: u8 = 201;
const PT_SDES: u8 = 202;
const PT_BYE: u8 = 203;
const PT_APP: u8 = 204;
const PT_RTPFB: u8 = 205;
const PT_PSFB: u8 = 206;
const PT_XR: u8 = 207;
const FMT_NACK: u8 = 1;
const FMT_TRANSPORT_CC: u8 = 15;
const FMT_PLI: u8 = 1;
const FMT_FIR: u8 = 4;
const FMT_REMB: u8 = 15;

/// Borrowed RTCP compound packet iterator.
#[derive(Debug, Clone)]
pub struct RtcpCompound<'a> {
    remaining: &'a [u8],
}

impl<'a> RtcpCompound<'a> {
    /// Parses an RTCP compound packet into an iterator.
    ///
    /// # Errors
    ///
    /// Returns an error when the compound packet is empty, exceeds 1500 bytes,
    /// or is shorter than one RTCP common header.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::{RtcpBuilder, RtcpCompound};
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_bye(9)?;
    /// assert_eq!(RtcpCompound::parse(builder.as_slice())?.count(), 1);
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    pub const fn parse(bytes: &'a [u8]) -> RtpResult<Self> {
        if bytes.len() > MAX_RTCP_COMPOUND_LEN {
            return Err(RtpError::RtcpCompoundTooLarge {
                len: bytes.len(),
                max: MAX_RTCP_COMPOUND_LEN,
            });
        }
        if bytes.len() < RTCP_HEADER_LEN {
            return Err(RtpError::RtcpPacketTooShort { len: bytes.len() });
        }
        Ok(Self { remaining: bytes })
    }

    /// Returns the Stage 1 stability marker for this public API.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::{rtcp::{RtcpBuilder, RtcpCompound}, Stability};
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_bye(9)?;
    /// assert_eq!(
    ///     RtcpCompound::parse(builder.as_slice())?.stability(),
    ///     Stability::Stage1
    /// );
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    #[must_use]
    pub const fn stability(&self) -> Stability {
        Stability::Stage1
    }
}

impl<'a> Iterator for RtcpCompound<'a> {
    type Item = RtpResult<RtcpPacket<'a>>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.remaining.is_empty() {
            return None;
        }
        if self.remaining.len() < RTCP_HEADER_LEN {
            let len = self.remaining.len();
            self.remaining = &[];
            return Some(Err(RtpError::RtcpPacketTooShort { len }));
        }
        let first = self.remaining[0];
        let version = first >> VERSION_SHIFT;
        if version != RTCP_VERSION {
            self.remaining = &[];
            return Some(Err(RtpError::InvalidVersion { version }));
        }
        let count = first & COUNT_MASK;
        let packet_type = self.remaining[1];
        let words = read_u16(&self.remaining[2..4]);
        let declared = (usize::from(words) + 1) * 4;
        if declared > self.remaining.len() {
            let remaining = self.remaining.len();
            self.remaining = &[];
            return Some(Err(RtpError::RtcpLengthTooLarge {
                declared,
                remaining,
            }));
        }
        let (packet, tail) = self.remaining.split_at(declared);
        self.remaining = tail;
        Some(parse_packet(count, packet_type, &packet[RTCP_HEADER_LEN..]))
    }
}

/// Parsed RTCP packet.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum RtcpPacket<'a> {
    /// Sender Report.
    SenderReport(SenderReport),
    /// Receiver Report.
    ReceiverReport(ReceiverReport<'a>),
    /// Source description packet.
    Sdes {
        /// SDES chunk count.
        count: u8,
        /// Raw SDES chunk bytes.
        chunks: &'a [u8],
    },
    /// Goodbye packet.
    Bye {
        /// SSRC/CSRC count.
        count: u8,
        /// Raw BYE body.
        body: &'a [u8],
    },
    /// Application-defined packet.
    App {
        /// APP subtype.
        subtype: u8,
        /// APP body.
        body: &'a [u8],
    },
    /// RTP feedback packet.
    Rtpfb(RtpFeedback<'a>),
    /// Payload-specific feedback packet.
    Psfb(PayloadFeedback<'a>),
    /// Extended report packet.
    Xr {
        /// Sender SSRC.
        sender_ssrc: u32,
        /// Raw XR report blocks.
        blocks: &'a [u8],
    },
}

impl RtcpPacket<'_> {
    /// Returns the Stage 1 stability marker for this public API.
    ///
    /// # Examples
    ///
    /// ```
    /// # use refract_rtp::rtcp::{RtcpBuilder, RtcpCompound};
    /// let mut builder = RtcpBuilder::new();
    /// builder.push_bye(9)?;
    /// let packet = RtcpCompound::parse(builder.as_slice())?
    ///     .next()
    ///     .transpose()?;
    /// assert_eq!(
    ///     packet.map(|item| item.stability()),
    ///     Some(refract_rtp::Stability::Stage1)
    /// );
    /// # Ok::<(), refract_rtp::RtpError>(())
    /// ```
    #[must_use]
    pub const fn stability(self) -> Stability {
        Stability::Stage1
    }
}

